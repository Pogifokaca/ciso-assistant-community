"""Rebrand the CISO Assistant UI as RegTech.

Changes only what users see: logo, favicon, page titles, UI texts, e-mail subjects.
Keeps translation keys, library URNs (urn:intuitem:...), LICENSE files and
copyright notices untouched. Safe to run more than once.
"""
import json, pathlib, re, shutil, sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
here = pathlib.Path(__file__).parent
fe, be = root / "frontend", root / "backend"
NAME = "RegTech"
PAT = re.compile(r"CISO[ -]Assistant")

def sub_file(path, pairs):
    p = root / path
    if not p.exists():
        print("skip (not found):", path); return
    s0 = s = p.read_text(encoding="utf-8")
    for a, b in pairs:
        s = s.replace(a, b)
    if s != s0:
        p.write_text(s, encoding="utf-8"); print("updated:", path)

# 1. Logo + favicon
shutil.copy(here / "regtech.svg", fe / "src/lib/assets/regtech.svg")
shutil.copy(here / "favicon.ico", fe / "static/favicon.ico")
sub_file("frontend/src/lib/components/Logo/Logo.svelte", [
    ("import ciso from '#lib/assets/ciso.svg';", "import ciso from '#lib/assets/regtech.svg';"),
    ('alt="Ciso-assistant icon"', 'alt="RegTech logo"'),
])
print("logo and favicon replaced")

# 2. UI texts in every language file (values only, never keys)
line_re = re.compile(r'^(\s*"(?:[^"\\]|\\.)*"\s*:\s*)(.*)$')
for f in sorted((fe / "messages").glob("*.json")):
    out = []
    for line in f.read_text(encoding="utf-8").split("\n"):
        m = line_re.match(line)
        out.append(m.group(1) + PAT.sub(NAME, m.group(2)) if m else PAT.sub(NAME, line))
    f.write_text("\n".join(out), encoding="utf-8")
    json.loads(f.read_text(encoding="utf-8"))  # must still be valid JSON
print("message files updated")

# Keep an honest attribution in the About dialog (AGPL-3.0 project)
for lang, text in {"en": "About RegTech (based on CISO Assistant)",
                   "mk": "За RegTech (базирано на CISO Assistant)"}.items():
    f = fe / "messages" / f"{lang}.json"
    if f.exists():
        s = f.read_text(encoding="utf-8")
        s = re.sub(r'("aboutCiso":\s*)"[^"]*"', lambda m: m.group(1) + json.dumps(text, ensure_ascii=False), s, count=1)
        f.write_text(s, encoding="utf-8")

# 3. Hard-coded names in Svelte pages (browser tab titles, chat widget, MFA issuer)
for p in [
    "frontend/src/routes/(app)/+layout.svelte",
    "frontend/src/routes/(authentication)/login/+page.svelte",
    "frontend/src/routes/(app)/setup-mfa/+page.svelte",
    "frontend/src/routes/(app)/(internal)/quantitative-risk-studies/[id=uuid]/executive-summary/+page.svelte",
    "frontend/src/routes/(app)/(third-party)/my-profile/settings/mfa/components/ActivateTOTPModal.svelte",
    "frontend/src/lib/components/ChatWidget/ChatWidget.svelte",
]:
    sub_file(p, [("CISO Assistant", NAME)])

# 4. Backend texts users see (e-mails, PDF footer, OIDC pages, API docs title, AI prompt)
for p, pairs in {
    "backend/iam/models.py": [('_("Welcome to CISO Assistant!")', '_("Welcome to RegTech!")')],
    "backend/iam/views.py": [('_("CISO Assistant: Password Reset")', '_("RegTech: Password Reset")')],
    "backend/global_settings/views.py": [('"CISO Assistant: outgoing mail', '"RegTech: outgoing mail')],
    "backend/doc_management/templates/doc_management/policy_document_pdf.html": [("Generated by CISO Assistant", "Generated by RegTech")],
    "backend/iam/templates/idp/oidc/authorization_form.html": [("CISO Assistant", NAME)],
    "backend/iam/templates/idp/oidc/authorization_refused.html": [("CISO Assistant", NAME)],
    "backend/iam/oidc_adapter.py": [('_("Use CISO Assistant through MCP")', '_("Use RegTech through MCP")')],
    "backend/iam/adapter.py": [('"name": "CISO Assistant"', '"name": "RegTech"')],
    "backend/ciso_assistant/settings.py": [('"TITLE": "CISO Assistant API"', '"TITLE": "RegTech API"'),
                                           ("with the CISO Assistant REST API", "with the RegTech REST API")],
    "backend/chat/providers.py": [("embedded in CISO Assistant", "embedded in RegTech")],
}.items():
    sub_file(p, pairs)
print("done")
